#!/usr/bin/env python3
"""Build the two ICCIT statistics tables as LaTeX (reviewer R1.4, 2026-11-18).

Table A (iccit/tables/tab_contrasts.tex): in-distribution paired contrasts,
mean difference with a Student-t 95% interval and Cohen's d_z, n=5 seeds.
Table B (iccit/tables/tab_loo_synth.tex): leave-one-dataset-out macro-F1 and
the synthetic sweeps.

Every number is read from per-seed JSONs under results/. Interval method is the
paper's: Student-t, n-1 = 4 df. The per-cell provenance for Table A is the
verified map in scripts/summarize_table2.py (imported, not re-derived).

Usage: python scripts/make_iccit_tables.py   (from the repo root)
"""
from __future__ import annotations

import json
import math
import os
import statistics as st
import sys

from scipy.stats import t as tdist

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import summarize_table2 as T2  # noqa: E402

SEEDS = T2.SEEDS
TCRIT = float(tdist.ppf(0.975, df=len(SEEDS) - 1))
OUT = os.path.join(ROOT, "outputs", "tables")
DATASETS = T2.DATASETS
SHORT = {"NF-UNSW-NB15-v2": "UNSW", "NF-BoT-IoT-v2": "BoT-IoT",
         "NF-CSE-CIC-IDS2018-v2": "CSE-CIC", "NF-ToN-IoT-v2": "ToN-IoT"}


def paired(a, b):
    """Return (mean, lo, hi, dz) of the paired difference a-b."""
    diff = [x - y for x, y in zip(a, b)]
    mu, sd = st.mean(diff), st.stdev(diff)
    half = TCRIT * sd / math.sqrt(len(diff))
    dz = mu / sd if sd else float("nan")
    return mu, mu - half, mu + half, dz


def fmt(r, digits=4):
    mu, lo, hi, dz = r
    return (f"${mu:+.{digits}f}$ [{lo:+.{digits}f}, {hi:+.{digits}f}] "
            f"({dz:+.2f})")


def load(path_fmt, key, **kw):
    out = []
    for s in SEEDS:
        with open(os.path.join(ROOT, path_fmt.format(seed=s, **kw))) as fh:
            out.append(json.load(fh)[key])
    return out


def table_contrasts():
    stats = {ds: {h: T2.load_per_seed(ds, h) for h in T2.HEADS}
             for ds in DATASETS}
    contrasts = [("GCP$-$GAP", "gcp", "gap"), ("GCP$-$SE", "gcp", "se"),
                 ("GCP$-$GMP", "gcp", "gmp"), ("GMP$-$GAP", "gmp", "gap")]
    rows = []
    for ds in DATASETS:
        cells = [fmt(paired(stats[ds][a], stats[ds][b]))
                 for _, a, b in contrasts]
        rows.append(f"    {SHORT[ds]} & " + " & ".join(cells) + r" \\")
    # Alternative backbone (reviewer run 2026-11-18, R1.5): TCN, same protocol.
    rows.append("    \\midrule")
    for ds in DATASETS:
        tcn = {h: load(f"results/reviewer_tcn/{{h}}_{ds}_{{seed}}.json",
                       "test", h=h) for h in T2.HEADS}
        tcn = {h: [x["macro_f1"] for x in v] for h, v in tcn.items()}
        cells = [fmt(paired(tcn[a], tcn[b])) for _, a, b in contrasts]
        rows.append(f"    {SHORT[ds]} (TCN) & " + " & ".join(cells) + r" \\")
    # Second alternative backbone (reviewer run 2026-11-19, R1.5): MLP, same protocol.
    rows.append("    \\midrule")
    for ds in DATASETS:
        mlp = {h: load(f"results/reviewer_mlp/{{h}}_{ds}_{{seed}}.json",
                       "test", h=h) for h in T2.HEADS}
        mlp = {h: [x["macro_f1"] for x in v] for h, v in mlp.items()}
        cells = [fmt(paired(mlp[a], mlp[b])) for _, a, b in contrasts]
        rows.append(f"    {SHORT[ds]} (MLP) & " + " & ".join(cells) + r" \\")
    head = " & ".join(n for n, _, _ in contrasts)
    return (
        "% generated by scripts/make_iccit_tables.py, do not edit by hand\n"
        "\\begin{table*}[t]\n  \\centering\n  \\scriptsize\n"
        "  \\renewcommand{\\arraystretch}{0.9}\n"
        "  \\setlength{\\tabcolsep}{2pt}\n"
        "  \\caption{Paired in-distribution contrasts, mean difference [95\\% CI] ($d_z$).}\n  \\label{tab:contrasts}\n"
        "  \\begin{tabular}{@{}lcccc@{}}\n    \\toprule\n"
        f"    Dataset & {head} \\\\\n    \\midrule\n"
        + "\n".join(rows) +
        "\n    \\bottomrule\n  \\end{tabular}\n\\end{table*}\n")


def loo_rows():
    rows = []
    for test in DATASETS:
        base = f"results/gap1/LOO__test-{test}__{{h}}__seed{{seed}}.json"
        leg = (f"results/gap1_gmp_legacy/LOO__test-{test}__gmp__seed{{seed}}"
               ".json")
        per = {h: load(base, "macro_f1", h=h) for h in ("gap", "se", "gcp")}
        gmp_path = os.path.join(ROOT, leg.format(seed=SEEDS[-1]))
        per["gmp"] = load(leg, "macro_f1") if os.path.exists(gmp_path) else None
        cells = [f"{st.mean(per[h]):.3f}" for h in ("gap", "se", "gcp")]
        cells.append(f"{st.mean(per['gmp']):.3f}" if per["gmp"] else "n/a")
        cells.append(fmt(paired(per["gcp"], per["gap"]), 3))
        cells.append(fmt(paired(per["gmp"], per["gap"]), 3)
                     if per["gmp"] else "n/a")
        rows.append(f"    {SHORT[test]} & " + " & ".join(cells) + r" \\")
    return rows


def synth_rows():
    strengths = ("0.0", "0.25", "0.5", "0.75", "1.0")
    sets = [("results/gateB_synthetic_n40k", "cov"),
            ("results/gateB_synthetic_far", "cov_far")]
    rows = []
    for s in strengths:
        cells = []
        for d, sig in sets:
            fmtp = f"{d}/{sig}__s{s}__{{h}}__seed{{seed}}.json" \
                if sig == "cov_far" else f"{d}/{sig}__s{s}__{{h}}__seed{{seed}}.json"
            try:
                per = {h: load(fmtp, "test_macro_f1", h=h)
                       for h in ("gap", "gmp", "gcp")}
            except FileNotFoundError:
                cells += ["n/a"] * 3
                continue
            cells.append(f"{st.mean(per['gap']):.3f}")
            cells.append(fmt(paired(per["gcp"], per["gap"]), 3))
            cells.append(fmt(paired(per["gcp"], per["gmp"]), 3))
        rows.append(f"    {s} & " + " & ".join(cells) + r" \\")
    return rows


def table_loo_synth():
    return (
        "% generated by scripts/make_iccit_tables.py, do not edit by hand\n"
        "\\begin{table*}[t]\n  \\centering\n  \\scriptsize\n"
        "  \\renewcommand{\\arraystretch}{0.9}\n"
        "  \\setlength{\\tabcolsep}{2pt}\n"
        "  \\caption{Leave-one-dataset-out (top) and synthetic (bottom) macro-F1, paired contrasts.}\n  \\label{tab:loosynth}\n"
        "  \\begin{tabular}{@{}lcccccc@{}}\n    \\toprule\n"
        "    Held-out & GAP & SE & GCP & GMP & GCP$-$GAP & GMP$-$GAP \\\\\n"
        "    \\midrule\n" + "\n".join(loo_rows()) +
        "\n    \\bottomrule\n  \\end{tabular}\n\n  \\vspace{4pt}\n"
        "  \\begin{tabular}{@{}lcccccc@{}}\n    \\toprule\n"
        "    & \\multicolumn{3}{c}{Original covariance regime} & "
        "\\multicolumn{3}{c}{Far-pair regime (leak-free)} \\\\\n"
        "    \\cmidrule(lr){2-4}\\cmidrule(l){5-7}\n"
        "    Strength & GAP & GCP$-$GAP & GCP$-$GMP & GAP & GCP$-$GAP & "
        "GCP$-$GMP \\\\\n    \\midrule\n" + "\n".join(synth_rows()) +
        "\n    \\bottomrule\n  \\end{tabular}\n\\end{table*}\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, body in (("tab_contrasts.tex", table_contrasts()),
                       ("tab_loo_synth.tex", table_loo_synth())):
        with open(os.path.join(OUT, name), "w") as fh:
            fh.write(body)
        print("wrote", os.path.join(OUT, name))


if __name__ == "__main__":
    main()
