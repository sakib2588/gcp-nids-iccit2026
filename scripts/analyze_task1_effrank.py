#!/usr/bin/env python3
"""Task 1 (effective-rank refinement) -- measure + regress, PER SAMPLE.

For every trained GCP checkpoint across widths {16,24,32,48,64,96,128} x 5 seeds:
  1. rebuild the model, load weights, run the backbone over a fixed val subsample,
  2. form the covariance the GCP head actually operates on. `covariance_pool`
     returns a PER-SAMPLE (B, C, C) tensor and the head takes the matrix square
     root of each sample's own matrix, so the spectrum is summarised per sample
     and the summaries are aggregated,
  3. measure effective rank + condition number per sample (src.metrics.eigen_summary
     semantics, vectorised), aggregate as mean effective rank and median
     log10(condition),
  4. pair with the per-(C, seed) GCP-GAP macro-F1 delta,
  5. regress delta against measured effective rank and log10(condition), with
     percentile-bootstrap CIs on Pearson + Spearman r (no parametric tests),
     at BOTH the per-checkpoint (n=35) and per-width (n=7) level.

WHY PER SAMPLE (audit defect B2, notes/20260720-bug-prepublication-code-audit.md).
The earlier revision of this script ran `covariance_pool(feat).mean(0)` and
summarised that average. Averaging thousands of rank-deficient PSD matrices
produces a full-rank, well-conditioned matrix that the model never sees. On
checkpoints/repro/NF-UNSW-NB15-v2__gcp__binary__seed42.pt over 512 val rows the
two objects differ by three orders of magnitude on the condition number at C=32
(per-sample ~1e5 against mean-of-cov ~2.5e2). Every mean-of-cov quantity is
still recorded here under the `meancov_*` keys so the two objects can be read
side by side, but the per-sample quantities are the ones that describe the
head's input.

The HDSS prediction: L'=33 is fixed, so measured effrank saturates near
min(C, L'-1=32); if the shrinkage story holds the delta tracks measured rank and
peaks at an interior width rather than growing monotonically with nominal C.

Output: results/task1/effrank_summary_persample.json. Analysis-only, CPU-only,
no training. The legacy mean-of-cov file results/task1/effrank_summary.json is
left in place for provenance and is NOT regenerated by this script.
"""
import os
import sys
import json

import numpy as np
import torch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from src import data as D                              # noqa: E402
from src.models import NIDSModel                       # noqa: E402
from src.gcp_layer import covariance_pool              # noqa: E402
from src.metrics import eigen_summary                  # noqa: E402

DATASET = "NF-UNSW-NB15-v2"
SEEDS = [42, 123, 456, 789, 1337]
WIDTHS = [16, 24, 32, 48, 64, 96, 128]
N_SUBSAMPLE = 8192
CHUNK = 2048                       # bounds peak memory at C=128
TOL_REL = 1e-8                     # eigen_summary's own noise floor
RESULTS_DIR = "results/task1"
OUT_NAME = "effrank_summary_persample.json"
TIER1_SUMMARY = "results/tier1/tier1_summary.json"

# reference rows from the audit note, reproduced as a correctness gate
REF_N_ROWS = 512
REF_SEED = 42


def gcp_ckpt_path(c, seed):
    """Resolve the GCP checkpoint for a (width, seed) across result dirs."""
    if c in (16, 64):
        return f"checkpoints/gap6/{DATASET}__gcp__binary__seed{seed}__C{c}.pt"
    if c == 32:
        return f"checkpoints/repro/{DATASET}__gcp__binary__seed{seed}.pt"
    if c == 128:
        return f"checkpoints/tier1/{DATASET}__gcp__binary__seed{seed}__C128.pt"
    return f"checkpoints/task1/{DATASET}__gcp__binary__seed{seed}__C{c}.pt"


def load_backbone(ckpt_path, device):
    ckpt = torch.load(ckpt_path, map_location="cpu", weights_only=False)
    c_last = ckpt.get("c_last", 32)
    model = NIDSModel(ckpt["head"], ckpt["n_classes"],
                      in_features=ckpt["in_features"],
                      channels=(16, 32, c_last),
                      backbone=ckpt.get("backbone", "cnn")).to(device)
    model.load_state_dict(ckpt["model_state_dict"])
    model.eval()
    return model, c_last


def batch_eigvals(ckpt_path, X, device):
    """Per-sample eigenvalues of the covariance the GCP head consumes.

    Forward runs in float32 (the trained precision); the feature map is then
    cast to float64 BEFORE forming the covariance, so the measured spectrum
    reflects the matrix itself rather than float32 rounding noise. In float32
    the rounding floor (~1e-7 relative) sits above eigen_summary's 1e-8 noise
    floor and manufactures spurious nonzero eigenvalues for the structurally
    rank-deficient C>L'-1 widths.

    Returns (eigvals (B, C) ascending, mean covariance (C, C)).
    """
    model, _ = load_backbone(ckpt_path, device)
    outs, cov_sum, n_seen = [], None, 0
    for i in range(0, len(X), CHUNK):
        xb = torch.from_numpy(X[i:i + CHUNK].astype(np.float32)).to(device)
        with torch.no_grad():
            feat = model.backbone(xb.unsqueeze(1)).double()   # (b, C, L')
            cov = covariance_pool(feat)                       # (b, C, C)
        cov_np = cov.cpu().numpy()
        outs.append(np.linalg.eigvalsh(cov_np))
        s = cov_np.sum(axis=0)
        cov_sum = s if cov_sum is None else cov_sum + s
        n_seen += cov_np.shape[0]
    return np.concatenate(outs, axis=0), cov_sum / n_seen


def summarise_eigs(W, tol_rel=TOL_REL):
    """Vectorised (effective_rank, condition, numerical_rank) per row of W.

    Row-for-row identical to src.metrics.eigen_summary applied to the matrix
    whose eigenvalues are that row; `assert_matches_eigen_summary` checks it.
    """
    W = np.clip(np.asarray(W, dtype=np.float64), 0.0, None)
    total = W.sum(axis=1)
    with np.errstate(divide="ignore", invalid="ignore"):
        P = np.where(total[:, None] > 0, W / total[:, None], 0.0)
        logP = np.where(P > 0, np.log(np.where(P > 0, P, 1.0)), 0.0)
    erank = np.exp(-(P * logP).sum(axis=1))
    wmax = W.max(axis=1)
    floor = tol_rel * wmax
    keep = W > floor[:, None]
    rank = keep.sum(axis=1)
    wmin = np.where(keep, W, np.inf).min(axis=1)
    cond = np.where(rank > 0, wmax / wmin, 1.0)
    degenerate = total <= 0
    erank = np.where(degenerate, 1.0, erank)
    cond = np.where(degenerate, 1.0, cond)
    return erank, cond, rank


def assert_matches_eigen_summary(cov_batch, n_check=16):
    """Guard: the vectorised path must agree with src.metrics.eigen_summary."""
    W = np.linalg.eigvalsh(cov_batch[:n_check])
    er, cd, _ = summarise_eigs(W)
    for b in range(min(n_check, len(cov_batch))):
        e0, c0 = eigen_summary(cov_batch[b])
        assert abs(er[b] - e0) < 1e-9 * max(1.0, e0), (er[b], e0)
        assert abs(cd[b] - c0) < 1e-6 * max(1.0, c0), (cd[b], c0)


def aggregate(W):
    """Per-checkpoint aggregate of the per-sample spectral summaries."""
    er, cd, rk = summarise_eigs(W)
    log10cd = np.log10(np.maximum(cd, 1.0))
    C = W.shape[1]
    return {
        "effrank_mean": float(er.mean()),
        "effrank_median": float(np.median(er)),
        "effrank_sd": float(er.std(ddof=1)),
        "cond_median": float(np.median(cd)),
        "cond_geomean": float(np.exp(np.mean(np.log(np.maximum(cd, 1.0))))),
        "log10_cond_median": float(np.median(log10cd)),
        "log10_cond_mean": float(log10cd.mean()),
        "rank_median": float(np.median(rk)),
        "rank_min": int(rk.min()),
        "rank_max": int(rk.max()),
        "frac_rank_deficient": float((rk < C).mean()),
    }


def _tier1():
    return json.load(open(TIER1_SUMMARY))["per_c"]


def _delta_existing(c, seed, per_c):
    """delta for widths held in tier1_summary, looked up BY SEED VALUE.

    Audit defect 1.13: the previous revision indexed the `gap`/`gcp` lists with
    SEEDS.index(seed) while run_tier1_cwidth.py silently dropped failed seeds,
    so one dropped seed would have shifted every later pairing. The summary now
    carries a `seeds` list; legacy files without it are only trusted when all
    five seeds are present, in which case the positional order is SEEDS.
    """
    s = per_c.get(str(c))
    if not s:
        return None
    seeds = s.get("seeds")
    if seeds is None:
        if len(s["gap"]) != len(SEEDS) or len(s["gcp"]) != len(SEEDS):
            print(f"[C{c}] legacy tier1_summary has no 'seeds' list and is not "
                  f"complete (gap={len(s['gap'])}, gcp={len(s['gcp'])}); "
                  f"alignment is unknowable, skipping width", flush=True)
            return None
        seeds = SEEDS
    if seed not in seeds:
        return None
    i = seeds.index(seed)
    return s["gcp"][i] - s["gap"][i]


def _delta_new(c, seed):
    """delta for the new widths from the per-cell result JSONs (seed in path)."""
    def f1(head):
        p = f"results/tier1/{DATASET}__{head}__binary__seed{seed}__C{c}.json"
        return json.load(open(p))["macro_f1"] if os.path.exists(p) else None
    g, gc = f1("gap"), f1("gcp")
    return (gc - g) if (g is not None and gc is not None) else None


def delta_for(c, seed, per_c):
    return (_delta_existing(c, seed, per_c) if c in (16, 32, 64, 128)
            else _delta_new(c, seed))


def corr_bootstrap(x, y, n_boot=10_000, seed=0):
    """Pearson + Spearman point estimate and percentile-95 CI via paired
    index resampling. No p-values (project protocol SS7)."""
    from scipy.stats import pearsonr, spearmanr
    x = np.asarray(x, float); y = np.asarray(y, float)
    n = len(x)
    rng = np.random.default_rng(seed)
    pe = float(pearsonr(x, y)[0]); se = float(spearmanr(x, y)[0])
    pb, sb = [], []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        xs, ys = x[idx], y[idx]
        # Exact-range check, not np.std(...) == 0. The standard deviation of k
        # copies of one float rounds to ~1e-15 rather than exactly 0, which
        # slips past a ==0 guard; scipy then flags constant input and returns
        # nan, and a single nan replicate makes np.percentile return nan for
        # the whole CI. At n=7 that happens in roughly 1 draw in 10,000.
        if np.ptp(xs) == 0 or np.ptp(ys) == 0:
            continue
        p = pearsonr(xs, ys)[0]; s = spearmanr(xs, ys)[0]
        if not (np.isfinite(p) and np.isfinite(s)):
            continue
        pb.append(p); sb.append(s)
    def ci(b):
        return [float(np.percentile(b, 2.5)), float(np.percentile(b, 97.5))]
    return {"pearson": pe, "pearson_ci": ci(pb),
            "spearman": se, "spearman_ci": ci(sb),
            "n_boot_used": len(pb)}


def reference_check(X_all, device):
    """Reproduce the audit's four reference rows on 512 val rows, seed 42.

    Reference (notes/20260720-bug-prepublication-code-audit.md, defect B2):
      per-sample  C=32 -> effrank 10.22, cond 4.59e5, rank 32
      mean-of-cov C=32 -> effrank 14.20, cond 2.49e2, rank 32
      per-sample  C=64 -> effrank 12.88, cond 4.90e2, rank 32 of 64
      mean-of-cov C=64 -> effrank 22.49, cond 5.03e2, rank 64
    """
    X = X_all[:REF_N_ROWS]
    out = {}
    for c in (32, 64):
        W, mcov = batch_eigvals(gcp_ckpt_path(c, REF_SEED), X, device)
        er, cd, rk = summarise_eigs(W)
        m_er, m_cd = eigen_summary(mcov)
        _, _, m_rk = summarise_eigs(np.linalg.eigvalsh(mcov)[None, :])
        out[f"C{c}"] = {
            "persample_effrank_mean": float(er.mean()),
            "persample_cond_median": float(np.median(cd)),
            "persample_cond_geomean": float(np.exp(np.mean(np.log(np.maximum(cd, 1.0))))),
            "persample_rank_median": float(np.median(rk)),
            "meancov_effrank": float(m_er),
            "meancov_cond": float(m_cd),
            "meancov_rank": int(m_rk[0]),
            "C": int(W.shape[1]),
        }
        r = out[f"C{c}"]
        print(f"  [ref C={c}] per-sample erank={r['persample_effrank_mean']:.2f} "
              f"cond_med={r['persample_cond_median']:.3e} "
              f"cond_geo={r['persample_cond_geomean']:.3e} "
              f"rank={r['persample_rank_median']:.0f} of {r['C']}", flush=True)
        print(f"  [ref C={c}] mean-of-cov erank={r['meancov_effrank']:.2f} "
              f"cond={r['meancov_cond']:.3e} rank={r['meancov_rank']}", flush=True)
    return out


def main():
    os.makedirs(RESULTS_DIR, exist_ok=True)
    device = torch.device("cpu")        # analysis-only, no GPU needed
    Xva, _ = D.load_split(DATASET, "val", D.DEFAULT_OUT, "binary")
    X = Xva[:N_SUBSAMPLE]
    lprime = X.shape[1] - 6  # 3 conv layers, kernel 3, no pad

    print("=== reference check (512 val rows, seed 42) ===", flush=True)
    ref = reference_check(Xva, device)

    per_c = _tier1()
    rows = []
    checked = False
    for c in WIDTHS:
        for seed in SEEDS:
            ck = gcp_ckpt_path(c, seed)
            d = delta_for(c, seed, per_c)
            if not os.path.exists(ck) or d is None:
                print(f"[C{c} seed{seed}] SKIP (ckpt or delta missing: {ck})",
                      flush=True)
                continue
            W, mcov = batch_eigvals(ck, X, device)
            if not checked:
                # one-off equivalence guard against src.metrics.eigen_summary
                model, _ = load_backbone(ck, device)
                xb = torch.from_numpy(X[:16].astype(np.float32)).to(device)
                with torch.no_grad():
                    cv = covariance_pool(model.backbone(xb.unsqueeze(1)).double())
                assert_matches_eigen_summary(cv.cpu().numpy())
                checked = True
            agg = aggregate(W)
            m_er, m_cd = eigen_summary(mcov)
            row = {"C": c, "seed": seed, "delta": float(d),
                   "lprime_over_c": lprime / c,
                   "meancov_effrank": float(m_er),
                   "meancov_condition": float(m_cd),
                   "meancov_log10_cond": float(np.log10(max(m_cd, 1.0)))}
            row.update(agg)
            rows.append(row)
            print(f"[C{c:3d} seed{seed}] delta={d:+.4f} "
                  f"erank={agg['effrank_mean']:6.2f} "
                  f"log10cond={agg['log10_cond_median']:5.2f} "
                  f"rank={agg['rank_median']:.0f}/{c} "
                  f"| meancov erank={m_er:6.2f} cond={m_cd:.3g}", flush=True)

    AGG_KEYS = ["delta", "effrank_mean", "log10_cond_median", "cond_median",
                "rank_median", "frac_rank_deficient", "meancov_effrank",
                "meancov_log10_cond", "meancov_condition"]
    per_width = {}
    for c in WIDTHS:
        rs = [r for r in rows if r["C"] == c]
        if not rs:
            continue
        w = {f"{k}_mean": float(np.mean([r[k] for r in rs])) for k in AGG_KEYS}
        w["n"] = len(rs)
        w["seeds"] = [r["seed"] for r in rs]
        per_width[str(c)] = w

    out = {"dataset": DATASET, "lprime": lprime, "n_subsample": N_SUBSAMPLE,
           "aggregation": {
               "object": "per-sample covariance_pool output (B, C, C)",
               "effrank": "mean over samples of per-sample effective rank",
               "condition": "median over samples of per-sample log10(condition)",
               "precision": "float32 forward, float64 covariance + eigendecomposition",
               "tol_rel": TOL_REL},
           "reference_check": ref,
           "per_checkpoint": rows, "per_width": per_width}

    if len(rows) >= 4:
        dl = [r["delta"] for r in rows]
        out["corr_pointlevel"] = {
            "n": len(rows),
            "delta_vs_effrank": corr_bootstrap([r["effrank_mean"] for r in rows], dl),
            "delta_vs_log10cond": corr_bootstrap([r["log10_cond_median"] for r in rows], dl),
            "delta_vs_effrank_meancov": corr_bootstrap([r["meancov_effrank"] for r in rows], dl),
            "delta_vs_log10cond_meancov": corr_bootstrap([r["meancov_log10_cond"] for r in rows], dl),
        }
    if len(per_width) >= 4:
        cs = sorted(per_width, key=lambda k: int(k))
        dm = [per_width[k]["delta_mean"] for k in cs]
        out["corr_widthmean"] = {
            "n": len(cs),
            "delta_vs_effrank": corr_bootstrap(
                [per_width[k]["effrank_mean_mean"] for k in cs], dm),
            # the per-width condition correlation the manuscript asserts but
            # which existed nowhere on disk before this run (audit, Manuscript
            # defects: "asserts four CIs cross zero. Three exist on disk.")
            "delta_vs_log10cond": corr_bootstrap(
                [per_width[k]["log10_cond_median_mean"] for k in cs], dm),
            "delta_vs_effrank_meancov": corr_bootstrap(
                [per_width[k]["meancov_effrank_mean"] for k in cs], dm),
            "delta_vs_log10cond_meancov": corr_bootstrap(
                [per_width[k]["meancov_log10_cond_mean"] for k in cs], dm),
        }
        peak = max(per_width, key=lambda k: per_width[k]["delta_mean"])
        out["peak_width"] = int(peak)

    with open(os.path.join(RESULTS_DIR, OUT_NAME), "w") as f:
        json.dump(out, f, indent=2)

    print("\n=== Task 1 effective-rank refinement (PER SAMPLE) ===", flush=True)
    for k in sorted(per_width, key=lambda x: int(x)):
        w = per_width[k]
        print(f"  C={int(k):3d}  delta={w['delta_mean']:+.4f}  "
              f"erank={w['effrank_mean_mean']:6.2f}  "
              f"log10cond={w['log10_cond_median_mean']:5.2f}  "
              f"rank={w['rank_median_mean']:6.2f}  "
              f"rankdef={w['frac_rank_deficient_mean']:.2f}  "
              f"| meancov erank={w['meancov_effrank_mean']:6.2f} "
              f"log10cond={w['meancov_log10_cond_mean']:.2f}", flush=True)
    for level in ("corr_pointlevel", "corr_widthmean"):
        if level not in out:
            continue
        print(f"  -- {level} (n={out[level]['n']})", flush=True)
        for key in ("delta_vs_effrank", "delta_vs_log10cond"):
            c = out[level][key]
            print(f"     {key:22s} pearson={c['pearson']:+.3f} "
                  f"CI[{c['pearson_ci'][0]:+.3f},{c['pearson_ci'][1]:+.3f}]  "
                  f"spearman={c['spearman']:+.3f} "
                  f"CI[{c['spearman_ci'][0]:+.3f},{c['spearman_ci'][1]:+.3f}]",
                  flush=True)
    if "peak_width" in out:
        print(f"  peak delta at C={out['peak_width']}", flush=True)
    print("TASK1_EFFRANK_PERSAMPLE_DONE", flush=True)


if __name__ == "__main__":
    main()
